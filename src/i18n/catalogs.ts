export const CATALOGS: Record<Locale, Record<MessageKey, string>> = {
  en,
  'zh-Hans': zhHans,
  ja,
}

export type { MessageKey }

export function translate(locale: Locale, key: string, params: Record<string, string | number> = {}): string {
  const catalog = CATALOGS[locale] as Record<string, string>
  const template = catalog[key] ?? (CATALOGS.en as Record<string, string>)[key] ?? key
  return template.replace(/\{([^}]+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`))
}
